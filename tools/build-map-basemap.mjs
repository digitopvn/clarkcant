#!/usr/bin/env node
/*
 * Builds the map widget's offline basemap from Natural Earth's 1:110m land polygons.
 *
 *   node tools/build-map-basemap.mjs <path to ne_110m_land.geojson>
 *
 * The source is downloaded by hand from the tagged Natural Earth release (see SOURCE below) and checked against its
 * SHA-256 here, so the module in the repository can always be rebuilt from the same bytes and compared. Natural Earth
 * is in the public domain (https://www.naturalearthdata.com/about/terms-of-use/), so the derived data can ship under
 * this repository's Apache-2.0 licence; the module still names its source.
 *
 * Coordinates are rounded to a tenth of a degree (about 11 km at the equator, below one pixel until zoom 5), repeated
 * points are dropped, and every ring is written as a delta-encoded list of integers. Nothing else is changed.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE = {
  name: "Natural Earth",
  dataset: "1:110m Physical Vectors, Land (ne_110m_land)",
  version: "5.1.2",
  url: "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson",
  sha256: "9e0729ee253ca7d7a5c4ae9395fb1902264c5377c52e224d13dd85010e2835d9",
  license: "Public domain (https://www.naturalearthdata.com/about/terms-of-use/)",
};
const SCALE = 10;
const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), "..", "packages", "conversation-client", "src", "map-basemap.ts");

const input = process.argv[2];
if (input === undefined) {
  console.error("usage: node tools/build-map-basemap.mjs <path to ne_110m_land.geojson>");
  process.exit(2);
}
const bytes = readFileSync(input);
const digest = createHash("sha256").update(bytes).digest("hex");
if (digest !== SOURCE.sha256) {
  console.error(`the source's SHA-256 is ${digest}, not the ${SOURCE.sha256} of Natural Earth ${SOURCE.version}`);
  process.exit(1);
}

const collection = JSON.parse(bytes.toString("utf8"));
const rings = [];
let points = 0;
for (const feature of collection.features) {
  const geometry = feature.geometry;
  const polygons = geometry.type === "Polygon" ? [geometry.coordinates] : geometry.type === "MultiPolygon" ? geometry.coordinates : [];
  for (const polygon of polygons) {
    for (const ring of polygon) {
      const quantized = [];
      for (const [lon, lat] of ring) {
        const point = [Math.round(lon * SCALE), Math.round(lat * SCALE)];
        const last = quantized.at(-1);
        if (last !== undefined && last[0] === point[0] && last[1] === point[1]) continue;
        quantized.push(point);
      }
      // A closed ring repeats its first point last; the renderer closes the path itself.
      const first = quantized[0];
      const end = quantized.at(-1);
      if (quantized.length > 1 && first[0] === end[0] && first[1] === end[1]) quantized.pop();
      if (quantized.length < 3) continue;
      const deltas = [];
      let previous = [0, 0];
      for (const point of quantized) {
        deltas.push(point[0] - previous[0], point[1] - previous[1]);
        previous = point;
      }
      points += quantized.length;
      rings.push(deltas.join(","));
    }
  }
}

const module = `/*
 * Generated by tools/build-map-basemap.mjs. Do not edit by hand; rebuild from the source below.
 *
 * Source: ${SOURCE.name}, ${SOURCE.dataset}, version ${SOURCE.version}
 *   ${SOURCE.url}
 *   SHA-256 ${SOURCE.sha256}
 * Licence: ${SOURCE.license}
 *
 * ${String(rings.length)} rings, ${String(points)} points, rounded to 1/${String(SCALE)} degree. Each ring is a list of integer
 * deltas: longitude then latitude, in 1/${String(SCALE)} degree, each from the point before it (the first from 0, 0).
 */

/** Where the offline basemap comes from, said beside every map that draws it. */
export const BASEMAP_SOURCE = {
  name: ${JSON.stringify(SOURCE.name)},
  dataset: ${JSON.stringify(SOURCE.dataset)},
  version: ${JSON.stringify(SOURCE.version)},
  license: "Public domain",
} as const;

const SCALE = ${String(SCALE)};

const RINGS: readonly string[] = [
${rings.map((ring) => `  ${JSON.stringify(ring)},`).join("\n")}
];

let decoded: readonly (readonly (readonly [number, number])[])[] | undefined;

/** The land rings as longitude and latitude pairs, decoded once. */
export function landRings(): readonly (readonly (readonly [number, number])[])[] {
  if (decoded !== undefined) return decoded;
  decoded = RINGS.map((ring) => {
    const values = ring.split(",").map(Number);
    const points: [number, number][] = [];
    let lon = 0;
    let lat = 0;
    for (let index = 0; index + 1 < values.length; index += 2) {
      lon += values[index] ?? 0;
      lat += values[index + 1] ?? 0;
      points.push([lon / SCALE, lat / SCALE]);
    }
    return points;
  });
  return decoded;
}
`;
writeFileSync(OUTPUT, module);
console.log(`wrote ${OUTPUT}: ${String(rings.length)} rings, ${String(points)} points, ${String(Buffer.byteLength(module))} bytes`);
